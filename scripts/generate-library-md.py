#!/usr/bin/env python3
"""Regenerate LIBRARY.md from the bundled app library.

Run from anywhere after editing Version Report/Resources/app-library.json:
    python3 scripts/generate-library-md.py
"""
import collections
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIBRARY_JSON = ROOT / "Version Report" / "Resources" / "app-library.json"
OUTPUT = ROOT / "LIBRARY.md"

LABELS = {
    "homebrew": "Homebrew Cask",
    "github": "GitHub Releases",
    "sparkle": "Sparkle Feed",
    "appstore": "App Store",
    "custom": "Custom",
}


def cell(text):
    return str(text).replace("|", "\\|").strip()


def source(entry):
    kind = entry.get("sourceType", "custom")
    label = LABELS.get(kind, kind)
    if kind == "homebrew":
        return f"[{label}](https://formulae.brew.sh/cask/{entry['caskName']})"
    if kind == "github":
        return f"[{label}](https://github.com/{entry['repoPath']})"
    if kind == "appstore":
        return f"[{label}]({entry['versionURL']})"
    return label


def main():
    entries = json.loads(LIBRARY_JSON.read_text())
    entries.sort(key=lambda e: e["name"].casefold())
    counts = collections.Counter(LABELS.get(e.get("sourceType", "custom"), "Custom") for e in entries)
    summary = ", ".join(f"{n} {label}" for label, n in counts.most_common())

    lines = [
        "# Built-in App Library",
        "",
        "<!-- Generated by scripts/generate-library-md.py from Version Report/Resources/app-library.json. Do not edit by hand. -->",
        "",
        f"Version Report ships with **{len(entries)} apps** in its built-in library ({summary}).",
        "Add any of them with **File → Add App From Library…** (⌥⌘L).",
        "",
        "Custom sources read a version from the vendor's own website or release notes.",
        "",
        "| App | Vendor | Source |",
        "|-----|--------|--------|",
    ]
    for e in entries:
        lines.append(f"| {cell(e['name'])} | {cell(e.get('vendor') or '')} | {source(e)} |")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} with {len(entries)} apps")


if __name__ == "__main__":
    main()
